"""
Generate the 4-file dataset for the enterprise_report template.

Models a financial-report shape with 3 levels of group nesting:
  groups[].sub_groups[].sub_groups[].rows[]

Produces:
  data/enterprise_<label>/
    disclaimers.json       small — 3 footer paragraphs
    metadata.json          small — report header info
    advisor_und.json       small — advisor info
    ticket_fee_detail.json large — the nested rows

Usage:
    python generate_enterprise_data.py 10000 100000 253000
"""
import os
import sys
import time
import random
import json

random.seed(42)

CURRENCIES = ["USD", "EUR", "GBP", "JPY", "CHF", "CAD", "AUD"]
SECURITIES = [
    "AAPL", "MSFT", "GOOGL", "AMZN", "TSLA", "META", "NVDA", "JPM", "V", "WMT",
    "BAC", "DIS", "NFLX", "PFE", "XOM", "CVX", "KO", "PEP", "ABBV", "TMO",
]
SIDES = ["BUY", "SELL"]
DESKS = ["Equities", "Fixed Income", "Derivatives", "FX", "Commodities", "Credit"]


def make_disclaimers():
    return {
        "report": (
            "This report is for informational purposes only and does not constitute "
            "investment advice. All figures are computed in the posting currency of "
            "the originating ticket and may differ from the booking currency due to "
            "FX settlement rates applied at end-of-day."
        ),
        "regulatory": (
            "Past performance is not indicative of future results. Trade-level data "
            "shown here reflects executions as recorded by the front-office systems "
            "and may be subject to subsequent adjustments by middle and back office "
            "reconciliation processes. Refer to the official statement of account "
            "for confirmed positions."
        ),
        "confidentiality": (
            "Confidential — this document contains proprietary information intended "
            "solely for the recipient named above. Any unauthorized review, use, "
            "disclosure, or distribution is prohibited. If you have received this "
            "report in error, contact the sender and delete all copies."
        ),
        "footnotes": [
            "(1) Trades flagged with an asterisk settled outside standard T+2 cycle.",
            "(2) Commission figures are net of regulatory and exchange fees.",
            "(3) Rates marked with a dagger are interpolated from end-of-day curves.",
        ],
        "end_disclaimer": (
            "End of report. Generated by the trade reporting platform. Questions "
            "regarding the figures shown here should be directed to your assigned "
            "advisor or the back-office reconciliation team."
        ),
    }


def make_metadata(seed):
    rnd = random.Random(seed)
    return {
        "report_title": "Ticket Fee Detail",
        "report_date": "2026-05-07",
        "account_number": f"ACCT-{rnd.randint(100000, 999999)}",
        "account_name": "Sample Institutional Client LP",
        "report_class": rnd.choice(["A", "B", "C", "D", "E"]),
        "num_headers": rnd.randint(2, 4),
        "page_size": "letter",
        "orientation": "landscape",
        "currency": "USD",
        "period_start": "2026-04-01",
        "period_end": "2026-04-30",
    }


def make_advisor(seed):
    rnd = random.Random(seed)
    return {
        "advisor_id": f"ADV-{rnd.randint(1000, 9999)}",
        "advisor_name": "John Q. Sample",
        "office": "New York",
        "phone": "+1-212-555-0100",
        "email": "j.sample@example.com",
        "team": rnd.choice(DESKS),
        "und_code": f"UND-{rnd.randint(100, 999)}",
    }


def make_row(rnd, idx, leaf_code):
    """Build one trade row. Some keys may be absent — exercises the
    `if "key" in row { row.key } else { none }` dispatch pattern."""
    row = {
        "ticket": f"{leaf_code}-{idx:06d}",
        "trade_date": f"2026-04-{rnd.randint(1, 30):02d}",
    }
    # Each optional column is present ~85% of the time. The remaining 15%
    # exercise the per-cell "if key in row" branch.
    if rnd.random() < 0.85:
        row["security"] = rnd.choice(SECURITIES)
    if rnd.random() < 0.85:
        row["side"] = rnd.choice(SIDES)
    if rnd.random() < 0.95:
        row["quantity"] = rnd.randint(1, 100000)
    if rnd.random() < 0.95:
        row["price"] = round(rnd.uniform(5, 500), 4)
    if rnd.random() < 0.90:
        qty = row.get("quantity", 0)
        px = row.get("price", 0)
        row["principal"] = round(qty * px, 2)
    if rnd.random() < 0.80:
        row["commission"] = round(rnd.uniform(1, 50), 2)
    if rnd.random() < 0.70:
        row["rate"] = round(rnd.uniform(0.0001, 0.05), 6)
    if rnd.random() < 0.60:
        row["basis"] = round(rnd.uniform(-10, 10), 4)
    row["posting_currency"] = rnd.choice(CURRENCIES)
    if rnd.random() < 0.10:
        row["asterisk"] = True
    return row


def distribute_rows(total_rows):
    """Pick a (leads × mids × leaves × rows_per_leaf) shape that adds
    up to ~total_rows. Aim for realistic-looking depths."""
    # Roughly: 50 leads × 25 mids × 4 leaves × N rows/leaf
    leads = max(10, min(50, total_rows // 5000))
    mids = max(5, min(25, total_rows // (leads * 200)))
    leaves = max(2, min(6, total_rows // (leads * mids * 50)))
    rows_per_leaf = max(5, total_rows // (leads * mids * leaves))
    return leads, mids, leaves, rows_per_leaf


def generate_ticket_fee_detail(path, total_rows):
    t0 = time.time()
    leads, mids, leaves, rows_per_leaf = distribute_rows(total_rows)
    rnd = random.Random(total_rows)

    # We stream-write JSON manually to avoid building the entire structure
    # in memory before serializing. Faster and lower-RAM for big sizes.
    written_rows = 0
    with open(path, "w", encoding="utf-8", buffering=1024 * 1024) as f:
        f.write('{"groups":[')
        for li in range(leads):
            if li > 0:
                f.write(",")
            lead_code = f"L{li:02d}"
            f.write(f'{{"name":"Lead Group {li + 1} — {DESKS[li % len(DESKS)]}",'
                    f'"code":"{lead_code}",'
                    f'"region":"{rnd.choice(["AMER", "EMEA", "APAC"])}",'
                    f'"sub_groups":[')
            for mi in range(mids):
                if mi > 0:
                    f.write(",")
                mid_code = f"{lead_code}-M{mi:02d}"
                f.write(f'{{"name":"Mid Group {mi + 1}","code":"{mid_code}",'
                        f'"strategy":"{rnd.choice(["Long-Short", "Macro", "Index", "Arb", "Quant"])}",'
                        f'"sub_groups":[')
                for fi in range(leaves):
                    if fi > 0:
                        f.write(",")
                    leaf_code = f"{mid_code}-F{fi:02d}"
                    f.write(f'{{"name":"Leaf {fi + 1}","code":"{leaf_code}",'
                            f'"book":"{rnd.choice(["Prop", "Agency", "Hedge", "Market"])}",'
                            f'"rows":[')
                    for ri in range(rows_per_leaf):
                        if ri > 0:
                            f.write(",")
                        row = make_row(rnd, ri, leaf_code)
                        json.dump(row, f)
                        written_rows += 1
                    f.write("]}")
                f.write("]}")
            f.write("]}")
        f.write("]}")
    size_mb = os.path.getsize(path) / (1024 * 1024)
    print(f"  ticket_fee_detail {written_rows:>10,} rows -> {size_mb:>8.1f} MB  ({time.time() - t0:.1f}s)")
    print(f"    shape: {leads} leads x {mids} mids x {leaves} leaves x {rows_per_leaf} rows/leaf")
    return written_rows


def generate_one(out_dir, total_rows):
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "disclaimers.json"), "w", encoding="utf-8") as f:
        json.dump(make_disclaimers(), f, indent=2, ensure_ascii=False)
    with open(os.path.join(out_dir, "metadata.json"), "w", encoding="utf-8") as f:
        json.dump(make_metadata(total_rows), f, indent=2, ensure_ascii=False)
    with open(os.path.join(out_dir, "advisor_und.json"), "w", encoding="utf-8") as f:
        json.dump(make_advisor(total_rows), f, indent=2, ensure_ascii=False)
    generate_ticket_fee_detail(
        os.path.join(out_dir, "ticket_fee_detail.json"),
        total_rows,
    )


if __name__ == "__main__":
    base = os.path.dirname(os.path.abspath(__file__))
    data_root = os.environ.get("TYPST_DATA_DIR", os.path.join(base, "data"))

    if len(sys.argv) > 1:
        sizes = [int(x.replace(",", "").replace("_", "")) for x in sys.argv[1:]]
    else:
        sizes = [10_000, 100_000, 253_000]

    for count in sizes:
        label = f"{count // 1000}k" if count >= 1000 else str(count)
        out_dir = os.path.join(data_root, f"enterprise_{label}")
        print(f"\nGenerating enterprise dataset @ {count:,} rows -> {out_dir}")
        generate_one(out_dir, count)
    print("\nDone.")
